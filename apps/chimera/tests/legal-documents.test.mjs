import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createServer } from 'vite';

const root = new URL('../', import.meta.url);
const read = (path) => readFile(new URL(path, root), 'utf8');

async function load() {
  process.env.VITE_SUPABASE_URL = 'https://synthetic.invalid';
  process.env.VITE_SUPABASE_ANON_KEY = 'synthetic-test-key';
  // react-router-dom only re-exports react-router and ships as CommonJS, which Node cannot import by name: the test uses react-router directly. React itself stays the one Node loads.
  const server = await createServer({ root: root.pathname, server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent', resolve: { alias: { 'react-router-dom': 'react-router' } }, ssr: { noExternal: ['react-router'] } });
  const get = (path) => server.ssrLoadModule(path);
  return {
    ...(await get('/src/legal/richText.ts')),
    ...(await get('/src/legal/markers.ts')),
    ...(await get('/src/legal/placeholders.ts')),
    ...(await get('/src/legal/terms.ts')),
    ...(await get('/src/legal/privacy.ts')),
    get,
    close: () => server.close(),
  };
}

const text = (doc, allStrings) => allStrings(doc).join('\n');

test('inline markup: bold, links, TODO (open and filled), confirm flags and unknown keys', async () => {
  const { parseInline, todoKeys, confirmFlags, close } = await load();
  try {
    assert.deepEqual(parseInline('a **b** [c](/terms) {{TODO:ENTITY_NAME}} {{CONFIRM: check this }} d').map((s) => s.kind), ['text', 'bold', 'text', 'link', 'text', 'todo', 'text', 'confirm', 'text']);
    assert.deepEqual(parseInline('{{TODO:NOT_A_KEY}}'), [{ kind: 'todo', key: 'NOT_A_KEY', label: 'NOT_A_KEY' }], 'an unknown key stays visible instead of vanishing');
    assert.equal(parseInline('{{TODO:ENTITY_NAME}}')[0].kind, 'todo');
    assert.deepEqual(todoKeys('{{TODO:A_B}} x {{TODO:C1}}'), ['A_B', 'C1']);
    assert.deepEqual(confirmFlags('{{CONFIRM: one }} {{CONFIRM:two}}'), ['one', 'two']);
    assert.deepEqual(parseInline('plain'), [{ kind: 'text', text: 'plain' }]);
  } finally { await close(); }
});

test('every missing detail is a registered placeholder, and nothing registered is unused: no invented values', async () => {
  const { PLACEHOLDERS, TERMS, PRIVACY, allStrings, todoKeys, close } = await load();
  try {
    const used = new Set([...allStrings(TERMS), ...allStrings(PRIVACY)].flatMap(todoKeys));
    for (const key of used) assert.ok(PLACEHOLDERS[key], `${key} is used but not registered`);
    for (const key of Object.keys(PLACEHOLDERS)) assert.ok(used.has(key) || key === 'EFFECTIVE_DATE', `${key} is registered but not used`);
    for (const [key, entry] of Object.entries(PLACEHOLDERS)) {
      assert.ok(entry.label.length > 5 && entry.question.length > 20, `${key} needs a label and a question`);
      assert.ok(entry.value === null || (typeof entry.value === 'string' && entry.value.trim().length > 0), `${key} must be null or a real answer`);
    }
  } finally { await close(); }
});

