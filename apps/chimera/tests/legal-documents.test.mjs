test('the documents match what the code does today (so a change in the code fails here until the text is updated)', async () => {
  const { TERMS, PRIVACY, allStrings, close } = await load();
  try {
    const terms = text(TERMS, allStrings);
    const privacy = text(PRIVACY, allStrings);

    // Age: the sign-up says 18, so do both documents.
    assert.match(await read('src/pages/AuthPage.tsx'), /18 years old or older/);
    assert.match(terms, /at least 18/); assert.match(privacy, /18 and over/);

    // Browser storage: exactly these files use it, and nothing sets cookies or uses IndexedDB.
    const files = [];
    const walk = async (dir) => {
      for (const entry of await readdir(new URL(dir, root), { withFileTypes: true })) {
        if (entry.isDirectory()) await walk(`${dir}${entry.name}/`);
        else if (/\.(ts|tsx)$/.test(entry.name)) files.push(`${dir}${entry.name}`);
      }
    };
    await walk('src/');
    const using = (needle) => { const hits = []; return Promise.all(files.map(async (f) => { if ((await read(f)).includes(needle)) hits.push(f); })).then(() => hits.sort()); };
    assert.deepEqual(await using('localStorage'), ['src/contexts/ModeContext.tsx', 'src/lib/chatLook.ts', 'src/lib/draftJournal.ts', 'src/lib/panelPrefs.ts'], 'new use of localStorage: update the Privacy Policy');
    assert.deepEqual(await using('sessionStorage'), ['src/pages/ShardsPage.tsx'], 'new use of sessionStorage: update the Privacy Policy');
    assert.deepEqual(await using('document.cookie'), [], 'cookies are now set by the code: update the Privacy Policy');
    assert.deepEqual(await using('indexedDB'), []);
    assert.match(await read('src/contexts/ModeContext.tsx'), /'chimera-mode'/);
    assert.match(privacy, /chimera-mode/);
    assert.match(await read('src/lib/panelPrefs.ts'), /'chimera\.chat\.panel\.open'/);
    assert.match(privacy, /chimera\.chat\.panel\.open/);
    assert.match(await read('src/lib/chatLook.ts'), /'chimera\.chat\.look'/);
    assert.match(privacy, /chimera\.chat\.look/);

    // No analytics or advertising libraries, no third-party scripts or styles in the page.
    const pkg = JSON.parse(await read('package.json'));
    const deps = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).join(' ');
    assert.ok(!/analytics|sentry|posthog|mixpanel|hotjar|gtag|plausible|segment|amplitude|fullstory/i.test(deps), 'a tracking library was added: update the Privacy Policy (cookies and sharing)');
    const html = await read('index.html');
    assert.ok(!/<script[^>]+src="https?:/i.test(html) && !/<link[^>]+href="https?:\/\/(?!www\.chimera)/i.test(html.replace(/rel="canonical"[^>]*>/, '')), 'third-party resources in index.html');

    // External services called by the server code: exactly the ones the Privacy Policy lists.
    const apiFiles = [];
    const walkApi = async (dir) => {
      for (const entry of await readdir(new URL(dir, root), { withFileTypes: true })) {
        if (entry.isDirectory()) await walkApi(`${dir}${entry.name}/`);
        else if (/\.ts$/.test(entry.name)) apiFiles.push(`${dir}${entry.name}`);
      }
    };
    await walkApi('api/');
    const hosts = new Set();
    for (const f of apiFiles) for (const m of (await read(f)).matchAll(/https?:\/\/([a-z0-9.-]+)/gi)) hosts.add(m[1]);
    hosts.delete('www.chimera.it.com');
    assert.deepEqual([...hosts].sort(), ['api.resend.com', 'generativelanguage.googleapis.com', 'openrouter.ai'], 'a new external service is called: add it to the Privacy Policy');
    assert.match(await read('api/create-shards-checkout.ts'), /from 'stripe'/);
    for (const name of ['Google', 'OpenRouter', 'Stripe', 'Supabase', 'Vercel', 'Resend']) assert.match(privacy, new RegExp(name));

    // The credits rules the product states on its own pages are in the Terms.
    const shardsPage = await read('src/pages/ShardsPage.tsx');
    assert.match(shardsPage, /non-transferable, non-withdrawable/);
    assert.match(terms, /cannot be transferred to another member/); assert.match(terms, /cannot convert SHARDS into VELLUM/);
    assert.match(await read('src/pages/VellumPage.tsx'), /cannot be transferred, withdrawn, or converted into SHARDS/);
  } finally { await close(); }
});

test('both documents render: banner, contents that point at real sections, visible TODO and confirm marks, and no raw markup', async () => {
  const { get, TERMS, PRIVACY, collectMarkers, close } = await load();
  try {
    // The same React instance must serve the page and this test, so these come from node itself, not from Vite.
    const react = await import('react');
    const { renderToStaticMarkup } = await import('react-dom/server');
    const { MemoryRouter } = await get('react-router-dom');
    const { LegalDocumentView } = await get('/src/components/legal/LegalDocumentView.tsx');
    for (const [doc, other] of [[TERMS, { to: '/privacy', label: 'Privacy Policy' }], [PRIVACY, { to: '/terms', label: 'Terms of Service' }]]) {
      const html = renderToStaticMarkup((react.default ?? react).createElement(MemoryRouter, null, (react.default ?? react).createElement(LegalDocumentView, { doc, other })));
      assert.ok(html.includes('DRAFT, NOT YET IN FORCE'), doc.title);
      assert.ok(html.includes(`<h1`) && html.includes(doc.title));
      const ids = [...html.matchAll(/<h2 id="([^"]+)"/g)].map((m) => m[1]);
      assert.deepEqual(ids, doc.sections.map((s) => s.id), `${doc.title}: one heading per section`);
      for (const id of ids) assert.ok(html.includes(`href="#${id}"`), `${doc.title}: contents link to ${id}`);
      assert.ok(html.includes('data-legal="todo"') && html.includes('data-legal="confirm"'));
      assert.ok(!html.includes('{{') && !html.includes('}}'), `${doc.title}: raw placeholder markup leaked`);
      assert.ok(!/\*\*[^*]/.test(html.replace(/<[^>]+>/g, '')), `${doc.title}: raw bold markup leaked`);
      assert.ok(html.includes(`href="${other.to}"`), 'links to the other document');
      const m = collectMarkers(doc);
      assert.ok(html.includes(`${m.openTodoKeys.length} details and ${m.confirmCount} choices are open`));
    }
  } finally { await close(); }
});

