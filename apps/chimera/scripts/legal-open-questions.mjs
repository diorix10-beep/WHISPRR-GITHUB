// Writes docs/legal/OPEN_QUESTIONS.md from the Terms and the Privacy Policy themselves, so the list can never drift from the text.
//   npm run legal:questions
import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';

process.env.VITE_SUPABASE_URL ??= 'https://synthetic.invalid';
process.env.VITE_SUPABASE_ANON_KEY ??= 'synthetic-key';
const root = new URL('../', import.meta.url).pathname;
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
try {
  const { PLACEHOLDERS } = await server.ssrLoadModule('/src/legal/placeholders.ts');
  const { TERMS } = await server.ssrLoadModule('/src/legal/terms.ts');
  const { PRIVACY } = await server.ssrLoadModule('/src/legal/privacy.ts');
  const { allStrings } = await server.ssrLoadModule('/src/legal/markers.ts');
  const { todoKeys, confirmFlags } = await server.ssrLoadModule('/src/legal/richText.ts');

  const docs = [['Terms', TERMS], ['Privacy', PRIVACY]];
  const usage = new Map(); // key -> ["Terms §3 Title", ...]
  const confirms = []; // [doc, section, text]
  for (const [name, doc] of docs) {
    for (const section of doc.sections) {
      const strings = allStrings({ ...doc, summary: [], sections: [section] }).slice(1); // drop the section title itself
      for (const key of new Set(strings.flatMap(todoKeys))) {
        if (!usage.has(key)) usage.set(key, []);
        usage.get(key).push(`${name}: ${section.title}`);
      }
      for (const text of strings.flatMap(confirmFlags)) confirms.push([name, section.title, text]);
    }
  }

  const groups = [
    ['Who operates CHIMERA, and how to reach it', ['ENTITY_NAME', 'ENTITY_REGISTRATION', 'REGISTERED_ADDRESS', 'CONTACT_EMAIL_SUPPORT', 'CONTACT_EMAIL_PRIVACY', 'CONTACT_EMAIL_REPORTS', 'CONTACT_EMAIL_LEGAL', 'IP_AGENT', 'EFFECTIVE_DATE']],
    ['Law and disputes (legal decisions: ask your lawyer)', ['GOVERNING_LAW', 'DISPUTE_FORUM', 'DISPUTE_PROCESS_DECISION', 'LIABILITY_CAP']],
    ['Money', ['PAYMENT_PROVIDER', 'MERCHANT_OF_RECORD', 'TAX_TREATMENT', 'REFUND_POLICY', 'CREDIT_EXPIRY', 'CLOSURE_BALANCE', 'SUBSCRIPTION_TERMS']],
    ['Creators (nothing of this exists in the product yet)', ['CREATOR_ELIGIBILITY', 'CREATOR_EARNINGS_SOURCES', 'PLATFORM_FEE', 'PAYOUT_PROVIDER', 'PAYOUT_TERMS', 'CREATOR_TAX_KYC', 'SUPPORTED_REGIONS']],
    ['Age and moderation', ['AGE_VERIFICATION_PROVIDER', 'APPEALS_PROCESS']],
    ['Privacy: providers, retention and rights', ['EMAIL_PROVIDER', 'AI_PROVIDER_SETTINGS', 'RETENTION_ACCOUNT', 'RETENTION_MESSAGES', 'RETENTION_LOGS', 'RETENTION_PAYMENTS', 'RETENTION_BACKUPS', 'RETENTION_MODERATION', 'DELETION_TIMELINE', 'EXPORT_PROCESS', 'TRANSFER_MECHANISM', 'EU_UK_REPRESENTATIVE', 'LOCAL_LAW']],
  ];
  const listed = new Set(groups.flatMap(([, keys]) => keys));
  const missingFromGroups = Object.keys(PLACEHOLDERS).filter((key) => !listed.has(key));
  if (missingFromGroups.length) groups.push(['Other', missingFromGroups]);

  const lines = [
    '# Legal drafts: what is still needed',
    '',
    '<!-- Generated by `npm run legal:questions` from src/legal/*. Do not edit by hand: change the placeholders or the text, then regenerate. -->',
    '',
    'The Terms (`/terms`) and the Privacy Policy (`/privacy`) are **drafts**. They describe only what the code and project documents establish.',
    'Everything else is a visible **TODO** (a fact we do not have) or **To confirm** (a choice drafted for you to approve).',
    'They are not legal advice and have not been reviewed by a lawyer.',
    '',
    '**How to fill one in:** set `value` for its key in `src/legal/placeholders.ts`; every place that uses the key is filled in at once.',
    '',
    `Open details: **${Object.values(PLACEHOLDERS).filter((p) => !p.value).length}**. Choices to confirm: **${confirms.length}**.`,
    '',
  ];
  for (const [title, keys] of groups) {
    lines.push(`## ${title}`, '');
    for (const key of keys) {
      const entry = PLACEHOLDERS[key];
      if (!entry) continue;
      lines.push(`### \`${key}\`${entry.value ? ' (filled)' : ''}`, '', entry.question, '', `Used in: ${(usage.get(key) ?? [key === 'EFFECTIVE_DATE' ? 'the top of each document' : '(not used)']).join('; ')}`, '');
    }
  }
  lines.push(
    '## What I found in the product that these documents depend on',
    '',
    'Checked in the code and in the production database on 9 October 2026. These are not text problems; they are things you may want to change or decide.',
    '',
    '- **No self-service deletion or export.** The database can record a deletion request (`request_chimera_data_removal`), but it only records it for review and nothing deletes automatically; no screen calls it. The Privacy Policy therefore says "write to us". Decide whether to build a screen.',
    '- **No in-app reporting or profile editing.** Reports and blocks have tables but no screen in CHIMERA, so the Terms ask people to e-mail a report address. Members cannot edit their profile name either.',
    '- **Older accounts have a name taken from the e-mail address.** Of 24 member profiles, 11 have a display name equal to the part of the e-mail before the "@" (from before the current sign-up), 10 have none. CHIMERA does not show these names to other members today, but they exist in the database.',
    '- **The terms accepted are only partly recorded.** The sign-up saves the accepted version in the account metadata (8 accounts). The `profiles` table has columns for the version, the time and the IP address, but the live sign-up trigger does not fill them (3 profiles have a version, none have an IP). The text only says that the version is saved with the account. Decide what you need to prove, then fill these.',
    '- **Re-accepting after the final text.** `CURRENT_LEGAL_VERSION` (src/contexts/AuthContext.tsx) was left unchanged on purpose: bump it when the final text is published. There is no mechanism yet that makes existing members accept a new version.',
    '- **AI request records hold the reply and have no clean-up.** `chimera_private.ai_requests` keeps the generated reply for retry safety. Decide how long to keep it (key `RETENTION_LOGS`).',
    '- **The shared Supabase project.** CHIMERA and WHISPRR store data in the same Supabase project. Decide whether accounts are shared and say so (see the "To confirm" flag in the Privacy Policy).',
    '- **Uploaded pictures are in a public bucket.** Anyone with the address of a character picture can open it, even if the character is private.',
    '- **The checkout does not collect consent for immediate delivery.** In the EU and UK this is normally needed to lose the 14-day withdrawal right on digital content (key `REFUND_POLICY`).',
    '- **Stripe.** The README notes that Stripe does not accept businesses in Senegal. If the operator is in Senegal, key `PAYMENT_PROVIDER` is an open problem, and Senegalese data-protection law (Law No. 2008-12, supervised by the CDP) may apply: please check with a lawyer (key `LOCAL_LAW`).',
    '- **"No ad watch" on the SHARDS page.** The SHARDS page says there is no ad watch. If you add rewarded ads, the page and the Privacy Policy (advertising and tracking) must change.',
    '- **Adult text with a General rating still passes at character creation.** The Terms forbid it, but nothing checks it yet.',
    '',
  );
  lines.push('## Choices drafted for you to confirm', '', 'Each of these appears in the text with a blue "To confirm" flag.', '');
  for (const [name, section, text] of confirms) lines.push(`- **${name}, ${section}:** ${text.replace(/\.$/, '')}.`);
  lines.push('');
  await writeFile(new URL('../docs/legal/OPEN_QUESTIONS.md', import.meta.url), lines.join('\n'));
  console.log(`Wrote docs/legal/OPEN_QUESTIONS.md (${Object.keys(PLACEHOLDERS).length} details, ${confirms.length} choices).`);
} finally {
  await server.close();
}
